#!/usr/bin/env python3
"""TCF — render every measured table into artifacts/tcf_summary_tables.md.

Run from repo root AFTER probes 1,2,2b,3,3b,4,4b,5,6,7,8:
    python -m experiments.stage_comparison_vector_architecture_opus.probes.tcf_tables
"""
from __future__ import annotations

import json
import pathlib

ART = pathlib.Path("experiments/stage_comparison_vector_architecture_opus/artifacts")
OUT = ART / "tcf_summary_tables.md"


def load(name):
    return json.loads((ART / name).read_text(encoding="utf-8"))


def table(headers, rows):
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(out)


def main() -> None:
    parts = ["# TCF — measured tables (generated by probes/tcf_tables.py)\n"]

    inv = load("tcf_inventory.json")
    parts.append("## 0. Inventory of the 20 Track A block descriptions\n")
    keys = ["pair", "side", "quality", "primitives", "segments_total", "segments_used", "segments_capped",
            "node_count", "edge_count", "components", "endpoints", "branch_points", "t_junctions",
            "x_crossings", "crossings_truncated", "closed_contours", "nested_contours"]
    parts.append(table(keys, [[r[k] for k in keys] for r in inv]))

    p1 = load("tcf_p1_tolerance.json")
    tols = [str(t) for t in p1["tolerances"]]
    parts.append("\n## 1a. Counts vs node-merge tolerance (left side of every pair)\n")
    rows = []
    for pair, sides in p1["raw"].items():
        for key in p1["comparator_keys"]:
            values = [sides["left"][t][key] for t in tols]
            lo = min(values) or 1
            rows.append([pair, key, *values, round(max(values) / lo, 2)])
    parts.append(table(["pair", "count", *tols, "max/min"], rows))

    parts.append("\n## 1b. Comparator topology similarity vs tolerance; `self` = the SAME block "
                 "compared against itself at another tolerance (pure artefact)\n")
    rows = []
    for row in p1["summary"]:
        rows.append([
            row["pair"],
            *[f"{row['pair_similarity_by_tolerance'][t]:.4f}" for t in tols],
            f"{row['pair_similarity_spread']:.4f}",
            f"{row['min_self_similarity']:.4f}",
        ])
    parts.append(table(["pair", *tols, "spread(pair)", "worst self-similarity"], rows))

    p2 = load("tcf_p2_cap.json")
    parts.append("\n## 2a. 8000-segment topology cap vs uncapped (tolerance 0.0025)\n")
    rows = []
    for block, row in p2["blocks"].items():
        for key in ("node_count", "edge_count", "connected_components", "endpoints", "branch_points",
                    "t_junctions", "x_crossings_unconnected"):
            rows.append([block, key, row["cap8000"][key], row["uncapped"][key],
                         round(row["uncapped"][key] / max(1, row["cap8000"][key]), 3)])
        rows.append([block, "segments collapsed to a self-loop", row["cap8000"]["collapsed_segments"],
                     row["uncapped"]["collapsed_segments"], ""])
    parts.append(table(["block", "count", "cap 8000", "uncapped", "ratio"], rows))

    parts.append("\n## 2b. Comparator topology similarity, capped vs uncapped\n")
    parts.append(table(["pair", "sim cap8000", "sim uncapped", "self: cap8000 vs uncapped"],
                       [[p, f"{r['similarity_cap8000']:.4f}", f"{r['similarity_uncapped']:.4f}",
                         f"{r['similarity_cap_vs_uncapped_same_block']:.4f}"] for p, r in p2["pairs"].items()]))

    parts.append("\n## 2c. What longest-first selection keeps\n")
    sel_keys = ["segments_total", "kept", "length_cutoff", "median_length_all", "median_length_kept",
                "median_length_dropped", "length_share_kept", "cell_coverage_kept",
                "axis_aligned_share_kept", "axis_aligned_share_dropped",
                "inside_text_bbox_share_kept", "inside_text_bbox_share_dropped",
                "long_share_kept", "long_share_all"]
    parts.append(table(["block", *sel_keys],
                       [[b, *[r["selection"][k] for k in sel_keys]] for b, r in p2["blocks"].items()]))

    p2b = load("tcf_p2b_capobjects.json")
    parts.append("\n## 2d. Objects lost to the cap\n")
    ok = ["primitives_with_segments", "fully_retained", "partially_retained_mutilated", "fully_dropped",
          "mutilated_share"]
    parts.append(table(["block", *ok], [[b, *[r[k] for k in ok]] for b, r in p2b["A_object_mutilation"].items()]))
    parts.append("\n### 2e. Circle aspect after block normalization (1.0 = a circle stays a circle)\n")
    parts.append(table(["block", "circles", "min aspect", "max aspect"],
                       [[b, r["circles"], r["min_aspect"], r["max_aspect"]]
                        for b, r in p2b.get("C_circle_aspect_after_normalization", {}).items()]))

    p3 = load("tcf_p3_crossings.json")
    p3b = load("tcf_p3b_same_path_crossings.json")
    parts.append("\n## 3a. Audit of `x_crossings_unconnected` (tolerance 0.0025, cap 8000, left side)\n")
    rows = []
    for block, r in p3["per_block"].items():
        rows.append([block, r["crossings"], r["truncated_at_5000"], r["share_near_endpoint"],
                     r["share_same_component"], r["share_joined_by_t_junction"],
                     p3b[block]["share_same_pdf_path"], p3b[block]["primitives_per_pdf_path"]])
    parts.append(table(["block", "crossings", "truncated@5000", "share within tolerance of an endpoint",
                        "share already in one component", "share already glued by a T-junction",
                        "share inside one PDF path", "primitives per PDF path"], rows))

    p4 = load("tcf_p4_curves.json")
    parts.append("\n## 4a. Cubic flattening error at CURVE_STEPS=6\n")
    ak = ["cubic_items_measured", "max_error_pt", "median_error_pt", "max_error_norm",
          "median_error_norm", "share_error_above_tolerance"]
    parts.append(table(["block", *ak], [[b, *[r[k] for k in ak]] for b, r in p4["A_cubic_flattening"].items()]))
    parts.append("\n## 4b. Circle census and the 24-gon inset\n")
    bk = ["circles", "median_radius_norm", "max_radius_norm",
          "circles_whose_24gon_inset_exceeds_tolerance", "radius_needed_to_exceed_tolerance"]
    parts.append(table(["block", *bk], [[b, *[r[k] for k in bk]]
                                        for b, r in p4["B_circle_census"].items() if isinstance(r, dict)]))
    parts.append("\n## 4c. Segment coverage similarity when the same circle is re-flattened (synthetic)\n")
    rows = []
    for radius, cases in p4["C_synthetic_reflattening_coverage"].items():
        for case, runs in cases.items():
            rows.append([radius, case, *[runs[t] for t in ("0.001", "0.0025", "0.005", "0.01")]])
    parts.append(table(["radius", "case", "tol 0.001", "0.0025", "0.005", "0.01"], rows))
    p4b = load("tcf_p4b_bezier.json")
    rows = []
    for radius, case in p4b["cases"].items():
        rows.append([radius, "24-gon route vs 4-cubic route",
                     *[case["route1_vs_route2"][t] for t in ("0.001", "0.0025", "0.005", "0.01")]])
        rows.append([radius, "4-cubic route vs same rotated start",
                     *[case["route2_vs_route2_rotated_start"][t] for t in ("0.001", "0.0025", "0.005", "0.01")]])
    parts.append("\n## 4d. The two REAL extractor routes for a circle (synthetic circle, both routes)\n")
    parts.append(table(["radius", "case", "tol 0.001", "0.0025", "0.005", "0.01"], rows))
    parts.append("\n## 4e. Normalization anisotropy: what 0.0025 normalized means in points\n")
    dk = ["block_width_pt", "block_height_pt", "aspect", "tolerance_pt_x", "tolerance_pt_y"]
    parts.append(table(["block", *dk], [[b, *[r[k] for k in dk]]
                                        for b, r in p4["D_normalization_anisotropy"].items()]))

    p5 = load("tcf_p5_nesting.json")
    parts.append("\n## 5. `nested_contours`\n")
    nk = ["closed_contours", "limit_1000_fires", "nested_track_a", "nested_share",
          "distinct_first_containers", "top_container_share_of_nested", "largest_contour_is_block_frame",
          "false_containment_share", "contours_depth_ge2", "contours_depth_ge3"]
    parts.append(table(["block", *nk], [[b, *[r[k] for k in nk]] for b, r in p5.items()]))

    p6 = load("tcf_p6_degree.json")
    parts.append(f"\n## 6. Degree histogram as a signature "
                 f"(NN == own pair partner: {p6['nearest_neighbour_is_pair_partner']}; "
                 f"partner closer than own tolerance jitter: {p6['partner_closer_than_tolerance_jitter']})\n")
    rk = ["nearest_neighbour", "nn_is_own_partner", "d_to_partner", "d_to_nearest_other_block",
          "d_to_self_at_tolerance_0.005", "d_to_self_at_tolerance_0.001"]
    parts.append(table(["block", *rk], [[r["block"], *[r[k] for k in rk]] for r in p6["rows"]]))

    p7 = load("tcf_p7_rotation.json")
    parts.append("\n## 7. Coordinate frame of the extracted block window\n")
    qk = ["rotation", "display_rect", "unrotated_rect", "iou_used_vs_meant", "block_outside_unrotated_page"]
    parts.append(table(["pair", "side", *qk], [[r["pair"], r["side"], *[r[k] for k in qk]] for r in p7]))

    p8 = load("tcf_p8_injection.json")
    parts.append("\n## 8. Injected engineering change vs the comparator\n")
    rows = []
    for block, r in p8["blocks"].items():
        for k, run in r["runs"].items():
            rows.append([block, r["segments_total"], r["segments_capped"], k, run["segments_added"],
                         run["topology_similarity"], run["geometry_similarity_selected"],
                         f"{run['branch_points'][0]}→{run['branch_points'][1]}",
                         f"{run['endpoints'][0]}→{run['endpoints'][1]}",
                         run["geometry_similarity_ge_0985"], run["topology_similarity_ge_085"]])
    parts.append(table(["block", "segments_total", "capped", "branches added", "segments added",
                        "topology sim", "geometry sim", "branch_points", "endpoints",
                        "geom >= 0.985", "topo >= 0.85"], rows))

    OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
