# Определения измерений даны дословно, потому что первый же замер показал
# расхождение моделей: одно и то же изменение площади Claude отнёс к SPACE,
# Codex — к QUANTITY. Без определений замер сравнивает не модели, а их догадки
# о значении слов.
DIMENSION_GUIDE = """\
PRINCIPLE  — сменилось проектное решение по существу (принцип работы системы).
METHOD     — сменился способ выполнения работ или технология.
OPERATION  — сменился порядок эксплуатации, режим, регламент.
STRUCTURE  — сменился состав конструкции: слои, элементы, набор частей.
CONNECTION — сменилась связь между элементами: подключение, примыкание, узел.
TYPE       — сменился тип/марка/материал изделия при том же назначении.
PARAMETER  — сменилось нормируемое свойство: толщина, класс, категория, отметка.
QUANTITY   — сменилось количество или числовая величина того же самого объекта.
SPACE      — сменилась геометрия помещения или его площадь, состав помещений.
UNKNOWN_DIMENSION — определить невозможно по имеющимся доказательствам."""

SYSTEM = """\
Ты — инженер-эксперт по проверке проектной документации многоквартирных домов.
Ты сравниваешь две редакции одного комплекта чертежей и классифицируешь одно
конкретное текстовое расхождение.

ЖЁСТКИЕ ПРАВИЛА:
1. Ты интерпретируешь доказательства, но НЕ создаёшь их. Любое значение в полях
   before_value / after_value / evidence_quotes обязано присутствовать ДОСЛОВНО
   во входном пакете. Выдуманное значение — грубейшая ошибка.
2. LEFT — старая редакция, RIGHT — новая. Не меняй стороны местами.
3. Если Stage 3 нашёл значение только слева, поле after_value обязано быть null,
   и наоборот.
4. Признать изменение (AI_RESOLVED) можно ТОЛЬКО когда ты уверен, что сравнение
   вообще правомерно: сопоставленные листы относятся к одному и тому же объекту,
   а сравниваемые строки описывают один и тот же элемент.
5. Если пара листов явно не соответствует друг другу (разные этажи, разные
   корпуса, разные по смыслу таблицы) — это НЕ изменение проекта. Отвечай
   HUMAN_REQUIRED с review_reason = SHEET_RELATION_WRONG.
6. Если строки таблиц сопоставлены не с теми (например разные коды помещений) —
   review_reason = ROW_ALIGNMENT_ARTIFACT.
7. Различия только в форматировании (запятая против точки в дробях, регистр,
   переносы, дублирование заголовка при распознавании) — это НЕ инженерное
   изменение: review_reason = FORMATTING_ONLY, outcome = DETAIL_ONLY.
8. Лучше честно отказаться, чем выдать уверенную ошибку. Отказ дёшев, ложная
   уверенность в проектной документации стоит дорого.

ИЗМЕРЕНИЯ (dimension):
""" + DIMENSION_GUIDE


def render_package(pkg: dict) -> str:
    """Человекочитаемое представление пакета — модели читают его лучше сырого JSON."""
    rel = pkg.get("sheet_relation") or {}
    det = pkg.get("deterministic_state") or {}

    lines = [
        "=== СОПОСТАВЛЕНИЕ ЛИСТОВ (на нём держится всё сравнение) ===",
        f"LEFT страницы {rel.get('left_pages')} <-> RIGHT страницы {rel.get('right_pages')}",
        f"тип: {rel.get('relation_type')}   статус: {rel.get('status')}   "
        f"уверенность алгоритма: {rel.get('confidence')}",
        f"признаки, по которым листы связаны: "
        f"{[e.get('feature') for e in (rel.get('evidence') or [])]}",
        "",
        "заголовки, фактически найденные на страницах LEFT:",
    ]
    lines += [f"   - {t}" for t in (pkg.get("left_page_titles") or ["(нет)"])]
    lines.append("заголовки, фактически найденные на страницах RIGHT:")
    lines += [f"   - {t}" for t in (pkg.get("right_page_titles") or ["(нет)"])]

    lines += [
        "",
        "=== РАСХОЖДЕНИЕ, НАЙДЕННОЕ ДЕТЕРМИНИРОВАННЫМ СРАВНЕНИЕМ ===",
        f"корзина Stage 3: {pkg.get('stage3_bucket')}   направление: {pkg.get('direction')}",
        f"BEFORE (LEFT):  {pkg.get('before_value')!r}",
        f"AFTER  (RIGHT): {pkg.get('after_value')!r}",
        "",
        "=== СОСЕДНИЙ КОНТЕКСТ LEFT (строка расхождения помечена ») ===",
    ]
    lines += (pkg.get("left_context") or ["  (сторона пуста)"])
    lines += ["", "=== СОСЕДНИЙ КОНТЕКСТ RIGHT (строка расхождения помечена ») ==="]
    lines += (pkg.get("right_context") or ["  (сторона пуста)"])

    lines += [
        "",
        "=== ЧТО УЖЕ УСТАНОВИЛ ДЕТЕРМИНИРОВАННЫЙ СЛОЙ ===",
        f"dimension: {det.get('dimension')}   outcome: {det.get('outcome')}",
        f"сущность проекта: {det.get('project_entity_ref')}   "
        f"структурный факт распознан: {det.get('structured_fact')}",
        f"коды причин: {det.get('reason_codes')}",
    ]
    return "\n".join(lines)


def analyst_prompt(pkg: dict) -> str:
    return (
        SYSTEM
        + "\n\n=== ПАКЕТ ДОКАЗАТЕЛЬСТВ ===\n"
        + render_package(pkg)
        + "\n\n=== ЗАДАЧА ===\n"
        "Классифицируй это расхождение и верни строго один объект JSON по заданной схеме.\n"
        "Поля before_value/after_value копируй ДОСЛОВНО из пакета (или null).\n"
        "В evidence_quotes приведи 1-3 дословные цитаты из показанного контекста.\n"
        "reasoning_summary и engineering_significance пиши по-русски."
    )


CRITIC_VERSION = "critic.v1"


def critic_prompt(pkg: dict, proposal: dict, verifier: dict) -> str:
    return (
        "Ты — придирчивый рецензент выводов другого инженера по проектной документации.\n"
        "Твоя задача — НАЙТИ ОШИБКУ, а не согласиться. По умолчанию сомневайся.\n\n"
        "Проверь предложение на:\n"
        "- выдуманные значения, которых нет в доказательствах;\n"
        "- перепутанные стороны LEFT/RIGHT;\n"
        "- неверное измерение (dimension) или направление;\n"
        "- вывод об изменении там, где на самом деле неверно сопоставлены листы\n"
        "  или строки таблиц (разные этажи, корпуса, разные коды помещений);\n"
        "- признание изменением того, что является различием форматирования;\n"
        "- завышенную уверенность при слабых доказательствах.\n\n"
        "Если предложение выдаёт изменение там, где сравнение неправомерно —\n"
        "verdict = HUMAN_REQUIRED.\n\n"
        "=== ПАКЕТ ДОКАЗАТЕЛЬСТВ ===\n" + render_package(pkg)
        + "\n\n=== ПРЕДЛОЖЕНИЕ АНАЛИТИКА ===\n"
        + json.dumps(proposal, ensure_ascii=False, indent=1)
        + "\n\n=== РЕЗУЛЬТАТ ДЕТЕРМИНИРОВАННОЙ ПРОВЕРКИ ===\n"
        + json.dumps(verifier, ensure_ascii=False)
        + "\n\nВерни строго один объект JSON по схеме. reasoning_summary — по-русски."
    )


SHEET_VERSION = "sheet_match.v1"


def sheet_prompt(left_pages: dict, right_pages: dict) -> str:
    def block(name, pages):
        out = [f"=== {name} ==="]
        for p in sorted(pages, key=int):
            titles = pages[p] or ["(заголовков не найдено)"]
            out.append(f"стр. {p}:")
            out += [f"    - {t}" for t in titles]
        return "\n".join(out)

    return (
        "Ты сопоставляешь листы двух редакций одного комплекта архитектурных чертежей.\n"
        "LEFT — старая редакция, RIGHT — новая.\n\n"
        "ПРАВИЛА:\n"
        "1. Связывай листы ТОЛЬКО когда они описывают один и тот же объект:\n"
        "   тот же этаж, тот же корпус, тот же тип таблицы.\n"
        "2. Экспликация помещений КВАРТИР и экспликация МОП — РАЗНЫЕ таблицы,\n"
        "   связывать их между собой нельзя.\n"
        "3. Разные этажи связывать нельзя. Разные корпуса связывать нельзя.\n"
        "4. Кровля и экспликация помещений — разные по смыслу листы.\n"
        "5. Номер страницы PDF сам по себе НЕ является основанием для связи.\n"
        "6. Если соответствия нет — честно отнеси лист в unmatched. Лишняя связь\n"
        "   порождает сотни ложных расхождений ниже по конвейеру.\n\n"
        + block("LEFT (старая редакция)", left_pages) + "\n\n"
        + block("RIGHT (новая редакция)", right_pages)
        + "\n\nВерни строго один объект JSON по схеме. В basis укажи дословный\n"
        "признак из заголовков, по которому связал. reasoning_summary — по-русски."
    )
