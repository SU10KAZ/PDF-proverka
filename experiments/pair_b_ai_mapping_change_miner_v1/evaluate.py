    checks=[]
    for line in ANCHORS.splitlines():
        i,op,ot,np,nt=line.split('|'); i=int(i)
        row=dict(change_id=changes[i]['change_id'],checks=[])
        for side,pages,terms in [('old',op,ot.split(';')),('new',np,nt.split(';'))]:
            sources=[]
            for page in map(int,pages.split(',')):
                path=OUT/'pages'/side/f'p{page:03d}.json'; data=read(path)
                sources.append(dict(page=page,text=norm(data['native']+'\n'+data['ocr']),sha256=sha(path)))
            for term in terms:
                matches=[dict(page=s['page'],source_sha256=s['sha256']) for s in sources if norm(term) in s['text']]
                row['checks'].append(dict(side=side,checked_pages=pages,anchor=term,
                    found=bool(matches),matches=matches))
        checks.append(row)
    # Review missing extraction literals before writing any final verdicts.
    missing=[dict(change_id=r['change_id'],**c) for r in checks for c in r['checks'] if not c['found']]
    if missing:
        print(missing)
        raise ValueError('Source anchors require inspection; no verdict files written')
