"""Single source of truth for completeness_requirements_matrix.

Each entry = one checklist item from
`backend/app/data/discipline_checklists/<DISCIPLINE>.md`, annotated with:

  - normative_status:
      "mandatory" | "conditionally_mandatory" | "recommended" | "optional"
      | "not_applicable"
  - applicable_document_types: subset of
      {"full_rd", "audit_comparison", "tz_vs_rd", "specification_only"}
  - applicable_stages: subset of {"ПД", "РД", "КМД"}
  - applicability_conditions: human-readable when conditional
  - normative_basis: cite the actual current norm
  - exact_clause_or_section: where to look in the norm
  - confidence: high / medium / low / unknown
  - can_be_reported_as_missing: True/False (gate for the lens)
  - recommended_severity: КРИТИЧЕСКОЕ / ЭКОНОМИЧЕСКОЕ / ЭКСПЛУАТАЦИОННОЕ
        / РЕКОМЕНДАТЕЛЬНОЕ / ПРОВЕРИТЬ_ПО_СМЕЖНЫМ
  - do_not_report_if: prompt-time guard text
  - example_valid_missing_case / example_invalid_missing_case
  - current_norm_issues: list of normative-correctness problems (e.g.
        outdated GOST number, phantom clause)

The build_matrix.py script imports ITEMS and writes both .json and .csv.

Conventions:
  - Each item gets a stable id: "<DISC>-<NN>" (zero-padded within discipline).
  - "current_*" prefix = state from backend checklist (what the source says).
  - "recommended_*" = our research verdict (what the lens SHOULD do).
"""
from __future__ import annotations


def _it(
    disc: str, idx: int, current_section: str,
    current_severity: str, current_applies: str, current_problem_class: str,
    current_norm: str,
    item_name: str,
    normative_status: str,
    applicable_document_types: list[str],
    applicable_stages: list[str],
    applicability_conditions: str = "",
    normative_basis: str = "",
    exact_clause: str = "",
    confidence: str = "medium",
    can_be_reported_as_missing: bool = True,
    recommended_severity: str = "ПРОВЕРИТЬ_ПО_СМЕЖНЫМ",
    do_not_report_if: str = "",
    example_valid: str = "",
    example_invalid: str = "",
    current_norm_issues: list | None = None,
) -> dict:
    return {
        "id": f"{disc}-{idx:02d}",
        "discipline": disc,
        "item_name": item_name,
        "current_section": current_section,
        "current_severity": current_severity,
        "current_applies": current_applies,
        "current_problem_class": current_problem_class,
        "current_norm_reference": current_norm,
        "normative_status": normative_status,
        "applicable_document_types": applicable_document_types,
        "applicable_stages": applicable_stages,
        "applicability_conditions": applicability_conditions,
        "normative_basis": normative_basis,
        "exact_clause_or_section": exact_clause,
        "confidence": confidence,
        "can_be_reported_as_missing": can_be_reported_as_missing,
        "recommended_severity": recommended_severity,
        "do_not_report_if": do_not_report_if,
        "example_valid_missing_case": example_valid,
        "example_invalid_missing_case": example_invalid,
        "current_norm_issues": list(current_norm_issues or []),
    }


