def match_rules() -> frozenset[str]:
    raw = (os.environ.get("VERSION_COMPARISON_MATCH_RULES") or MATCH_RULES_DEFAULT).strip().lower()
    if raw == "v1":
        return frozenset()
    if raw == "v1.1":
        return frozenset(MATCH_RULES_V11)
    if raw == "v1.2":
        return frozenset(MATCH_RULES_V12)
    if raw == "v1.3":
        return frozenset(MATCH_RULES_V13)
    if raw.startswith("v1.2+"):
        return frozenset(MATCH_RULES_V12) | {x for x in raw[5:].split("+") if x in MATCH_RULE_PARTS}
    if raw.startswith("v1.1+"):
        return frozenset(MATCH_RULES_V11) | {x for x in raw[5:].split("+") if x in MATCH_RULE_PARTS}
    return frozenset(x.strip() for x in raw.split(",") if x.strip() in MATCH_RULE_PARTS)


def match_rules_tag(rules: frozenset[str] | None = None) -> str:
    rules = match_rules() if rules is None else rules
    return "" if not rules else "rules=" + ",".join(sorted(rules))
