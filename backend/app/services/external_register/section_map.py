def lookup(section_code: str) -> Optional[str]:
    """Вернуть относительный путь подпроекта или None если не найден."""
    if not section_code:
        return None
    return SECTION_TO_PROJECT.get(section_code.strip())


def all_known_codes() -> list[str]:
    """Список всех знакомых кодов (для диагностики/UI)."""
    return sorted(SECTION_TO_PROJECT.keys())
