"""Промпты ИИ-слоя. Один текст — один контракт, версия рядом со схемой.

Промпт здесь делает ровно три вещи: объясняет, что перед моделью не проект, а
одно расхождение; перечисляет запреты, нарушение которых верификатор всё равно
поймает; и требует отказаться, когда доказательств не хватает. Отказ — это
рабочий ответ, а не провал: HUMAN_REQUIRED с внятной причиной полезнее
уверенного вымысла, который потом придётся ловить инженеру.
"""
from __future__ import annotations

import json
from typing import Any, Mapping, Sequence

from . import schemas

ANALYST_SYSTEM_PROMPT = (
    "Ты — инженер-эксперт по проектной документации многоквартирных домов. "
    "Ты сравниваешь две редакции одного листа и отвечаешь строго по схеме. "
    "Ты не имеешь права придумывать значения: всё, что ты называешь фактом "
    "документа, обязано дословно присутствовать во входных доказательствах."
)

_RULES = """ПРАВИЛА

1. Перед тобой ОДНА пара листов и несколько расхождений на ней. Ты не видишь
   остальной проект и не должен о нём рассуждать.
2. before_value и after_value — ТОЧНЫЕ подстроки из доказательств своей
   стороны. Не пересказ, не нормализация, не перевод единиц.
   Значение слева ищется только в left_context, справа — только в
   right_context. Ответ, где стороны переставлены, будет отклонён.
3. evidence_quotes — дословные строки из тех же доказательств. Цитата, которой
   там нет, отклоняет весь ответ. Знак «»» в начале строки контекста — это
   пометка «вот эта строка», а не текст документа: в цитату его не включай.
4. object_label — название объекта на языке проекта: «помещение 24.5»,
   «кровля К5», «ВРУ-1». Никаких внутренних идентификаторов
   (project_entity_ref, text_entity:…, ureview_…): их ставит система сама.
5. Координат и рамок не выдумывай: их у тебя нет.
6. Если доказательств не хватает, пара листов выглядит неверной, строки
   таблицы сопоставлены не с теми или различие сводится к записи и OCR —
   отвечай resolution_status = HUMAN_REQUIRED, needs_human_review = true,
   назови причину в human_reason и сформулируй human_question по-русски так,
   чтобы инженер ответил за десять секунд.
7. resolution_status = AI_RESOLVED допустим ТОЛЬКО когда: тип изменения
   определён (не UNKNOWN_DIMENSION), объект назван, значение подтверждено
   цитатой и уверенность не UNKNOWN.
8. outcome: MATERIAL_CHANGE — меняет проектное решение; DETAIL_ONLY — уточнение
   без последствий; REVIEW_REQUIRED — нужен инженер.
9. Отвечай ровно по одному разрешению на каждый элемент пакета, ни больше ни
   меньше, и копируй item_id дословно.
10. engineering_summary — одно-два предложения по-русски о том, что это значит
    для проекта. Не пересказ своих рассуждений."""

_DIMENSION_GUIDE = """ТИПЫ ИЗМЕНЕНИЯ (dimension)

PRINCIPLE — сменилось проектное решение целиком
METHOD    — сменился способ выполнения
OPERATION — сменился порядок работы/эксплуатации
STRUCTURE — сменился состав: слой, элемент, узел добавлен или убран
CONNECTION— сменилась связь: питание, примыкание, подключение
TYPE      — сменился тип/марка/материал
PARAMETER — сменилось числовое свойство: толщина, площадь, мощность
QUANTITY  — сменилось количество
SPACE     — сменилось расположение или геометрия
UNKNOWN_DIMENSION — определить нельзя (тогда outcome обязан быть REVIEW_REQUIRED)"""


def analyst_prompt(package_view: Mapping[str, Any]) -> str:
    """Промпт массового аналитика на одну партию элементов."""
    return "\n\n".join([
        "ЗАДАЧА. Ниже пара листов двух редакций одного проекта и найденные на "
        "ней расхождения. По каждому реши: что изменилось, у какого объекта, "
        "с какого значения на какое — или честно откажись.",
        _RULES,
        _DIMENSION_GUIDE,
        "ВХОДНЫЕ ДАННЫЕ (JSON)",
        json.dumps(package_view, ensure_ascii=False, indent=1),
        "Ответь строго по схеме ответа.",
    ])


CRITIC_SYSTEM_PROMPT = (
    "Ты — придирчивый рецензент. Твоя задача — НАЙТИ ошибку в чужом разборе, "
    "а не согласиться с ним. Если сомневаешься, отклоняй."
)


def critic_prompt(
    item_view: Mapping[str, Any],
    resolution: Mapping[str, Any],
) -> str:
    """Промпт выборочного критика: одно разрешение, одна попытка опровергнуть."""
    return "\n\n".join([
        "ЗАДАЧА. Проверь чужой разбор одного расхождения между двумя "
        "редакциями листа. Ищи именно ошибку: выдуманное значение, не тот "
        "объект, перепутанные стороны, неверный тип изменения, "
        "неучтённое противоречие, чрезмерную уверенность.",
        "Отклоняй (verdict = REJECT), если вывод не следует из доказательств. "
        "Ставь HUMAN_REQUIRED, если решить может только инженер. "
        "ACCEPT — только когда вывод доказан приведёнными цитатами. "
        "Объяснение пиши по-русски и для инженера, а не для разработчика.",
        "ДОКАЗАТЕЛЬСТВА (JSON)",
        json.dumps(item_view, ensure_ascii=False, indent=1),
        "РАЗБОР, КОТОРЫЙ ТЫ ПРОВЕРЯЕШЬ (JSON)",
        json.dumps(resolution, ensure_ascii=False, indent=1),
        "Ответь строго по схеме ответа.",
    ])


VISION_SYSTEM_PROMPT = (
    "Ты читаешь фрагменты чертежей. Говори только о том, что действительно "
    "видно на изображении."
)


def vision_prompt(
    item_view: Mapping[str, Any],
    resolution: Mapping[str, Any] | None,
    captions: Sequence[str] | None = None,
) -> str:
    """Промпт визуального резерва: чертёж как подтверждение, а не как истина."""
    if captions:
        images = "ИЗОБРАЖЕНИЯ ПО ПОРЯДКУ\n" + "\n".join(
            f"{index}. {caption}" for index, caption in enumerate(captions, 1)
        )
    else:
        images = (
            "ИЗОБРАЖЕНИЯ ПО ПОРЯДКУ\n"
            "1. левая (старая) редакция\n2. правая (новая) редакция"
        )
    parts = [
        "ЗАДАЧА. Даны изображения чертежа. Текстовый разбор этого места "
        "оказался недостаточным.",
        images,
        "ПРАВИЛА\n"
        "1. Опиши только то, что реально видно. Не достраивай по смыслу.\n"
        "2. Текст штампа и текстового слоя — первичен. Если изображение ему "
        "противоречит, это повод для verdict = CONTRADICTS_TEXT, а не повод "
        "переписать текст: на реальном листе модель уже читала «Корпус 1» "
        "вместо «Корпус 4».\n"
        "3. Если показан ЛИСТ ЦЕЛИКОМ, это значит, что с этой стороны у "
        "элемента нет координат: строку надо искать по всему листу. "
        "Отсутствие искомого значения на листе — полноценное наблюдение, а не "
        "повод сказать «не видно»; так и напиши: значения на листе нет.\n"
        "4. Если по картинке действительно не видно — INSUFFICIENT_IMAGE. Это "
        "нормальный ответ.\n"
        "5. Отвечай по-русски.",
        "ЧТО УЖЕ ИЗВЕСТНО ИЗ ТЕКСТА (JSON)",
        json.dumps(item_view, ensure_ascii=False, indent=1),
    ]
    if resolution is not None:
        parts += [
            "ТЕКСТОВЫЙ ВЫВОД, КОТОРЫЙ НАДО ПОДТВЕРДИТЬ ИЛИ ОПРОВЕРГНУТЬ (JSON)",
            json.dumps(resolution, ensure_ascii=False, indent=1),
        ]
    parts.append("Ответь строго по схеме ответа.")
    return "\n\n".join(parts)


