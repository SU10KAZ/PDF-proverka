def variant_sha256() -> str:
    payload = f"{VARIANT_ID}\n{SYSTEM_B_V1}\n{USER_ADDENDUM_B_V1}".encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def messages_for_arm(arm: str, production_messages: list[dict]) -> list[dict]:
    """Сообщения плеча: A — боевые без изменений, B — замена system и дополнение user."""
    if arm == "A":
        return [dict(m) for m in production_messages]
    if arm != "B":
        raise ValueError(f"unknown arm {arm!r}")
    if [m.get("role") for m in production_messages] != ["system", "user"]:
        raise ValueError("ожидались ровно system + user сообщения боевого _docnorm_messages")
    system, user = production_messages
    return [
        {"role": "system", "content": SYSTEM_B_V1},
        {"role": "user", "content": str(user.get("content") or "") + USER_ADDENDUM_B_V1},
    ]
